// 提示词指纹随之漂移，跨 depth 的发言缓存全部落空，
// 「只改一个阶段」的对照实验也因此不再是单变量。
//
// depth 该做的事全部在 entities.NewPlan 里：决定跑哪些阶段。成员不需要知道它。
